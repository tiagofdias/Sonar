import { test } from "node:test";
import assert from "node:assert/strict";
import express from "express";
import cookieParser from "cookie-parser";
import jwt from "jsonwebtoken";
import mongoose from "mongoose";
import { MongoMemoryReplSet } from "mongodb-memory-server";
import { OlmMachine, UserId, DeviceId, RequestType } from "@matrix-org/matrix-sdk-crypto-wasm";
import { createMatrixDeviceRouter } from "./matrixDevice.route.js";
import { createMatrixMessagingRouter } from "./matrixMessaging.route.js";
import User from "../models/user.model.js";
import LoginSession from "../models/loginSession.model.js";
import MatrixDevice from "../models/matrixDevice.model.js";
import MatrixAccount from "../models/matrixAccount.model.js";
import MatrixEnrollment from "../models/matrixEnrollment.model.js";
import MatrixBindingChallenge from "../models/matrixBindingChallenge.model.js";
import MatrixRoomEvent from "../models/matrixRoomEvent.model.js";
import { createSession, sessionHash } from "../lib/sessions.js";
import { signMatrixEnrollment } from "../../../frontend/src/lib/matrixEnrollment.js";
import { signMatrixBinding } from "../../../frontend/src/lib/matrixBinding.js";
import { bootstrapMatrixDevice } from "../lib/matrixEnrollment.js";
import { createMatrixRoom } from "../lib/matrixRooms.js";
import { revokeSessionMatrixDevice } from "../lib/matrixKeys.js";

test("experimental device endpoints require a tracked session and never approve registration", async () => {
  process.env.JWT_SECRET = process.env.JWT_SECRET || "synthetic-matrix-device-test-jwt-secret";
  assert.throws(() => createMatrixDeviceRouter("bad..domain"));
  const db = await MongoMemoryReplSet.create({ replSet: { count: 1 } });
  let server, machine;
  try {
    await mongoose.connect(db.getUri("sonar-matrix-route-test"));
    await Promise.all([User.init(), LoginSession.init(), MatrixDevice.init(), MatrixAccount.init(), MatrixEnrollment.init(), MatrixBindingChallenge.init()]);
    const account = await User.create({ fullName: "Synthetic", email: "route@example.invalid", password: "unused-test-hash" });
    const peer = await User.create({ fullName: "Synthetic peer", email: "route-peer@example.invalid", password: "unused-test-hash" });
    const accountId = String(account._id), userId = `@${accountId}:sonar.invalid`;
    const rawSession = await createSession(accountId, 0, "password");
    const cookie = `jwt=${jwt.sign({ userId: accountId, sessionVersion: 0, sessionId: rawSession }, process.env.JWT_SECRET)}`;
    const legacyCookie = `jwt=${jwt.sign({ userId: accountId, sessionVersion: 0 }, process.env.JWT_SECRET)}`;
    const notifications = [];
    const app = express(); app.use(express.json()); app.use(cookieParser()); app.use("/device", createMatrixDeviceRouter("sonar.invalid")); app.use("/message", createMatrixMessagingRouter("sonar.invalid", { notify: members => notifications.push(members) }));
    await new Promise(resolve => { server = app.listen(0, "127.0.0.1", resolve); });
    const base = `http://127.0.0.1:${server.address().port}`;
    const request = (path, body, auth = cookie) => fetch(base + "/device" + path, { method: body ? "POST" : "GET", headers: { ...(auth ? { Cookie: auth } : {}), ...(body ? { "Content-Type": "application/json" } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    const message = (path, body, auth = cookie) => fetch(base + "/message" + path, { method: body ? "POST" : "GET", headers: { ...(auth ? { Cookie: auth } : {}), ...(body ? { "Content-Type": "application/json" } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    assert.equal((await request("/identity", null, "")).status, 401);
    assert.equal((await request("/identity", null, legacyCookie)).status, 401);
    assert.deepEqual(await (await request("/identity")).json(), { userId });
    assert.equal((await request("/list")).status, 400);
    machine = await OlmMachine.initialize(new UserId(userId), new DeviceId("WEB"));
    const keys = JSON.parse((await machine.outgoingRequests()).find(item => item.type === RequestType.KeysUpload).body).device_keys;
    const challenge = await (await request("/enroll/challenge", { deviceId: "WEB", deviceKeys: keys })).json();
    const signature = await signMatrixEnrollment(machine, userId, "WEB", keys, challenge);
    const complete = await request("/enroll/complete", { deviceId: "WEB", token: challenge.token, signature });
    assert.equal(complete.status, 200);
    assert.equal((await complete.json()).serverAuthorization, "pending");
    assert.equal((await request("/enroll/complete", { deviceId: "WEB", token: challenge.token, signature })).status, 400);
    const bind = await (await request("/bind/challenge", { deviceId: "WEB" })).json();
    const bindingSignature = await signMatrixBinding(machine, userId, "WEB", bind);
    assert.equal((await request("/bind/complete", { deviceId: "WEB", token: bind.token, signature: bindingSignature })).status, 200);
    assert.equal((await MatrixDevice.findOne({ userId, deviceId: "WEB" })).serverAuthorization, "pending");
    const list = await (await request("/list")).json();
    assert.equal(list.devices.length, 1);
    assert.equal(list.devices[0].deviceId, "WEB");
    assert.equal(list.devices[0].serverAuthorization, "pending");
    assert.equal(list.devices[0].current, true);
    assert.equal(list.devices[0].ed25519, keys.keys["ed25519:WEB"]);
    assert.equal(Object.hasOwn(list.devices[0], "verified"), false);
    assert.equal((await request("/bootstrap", { deviceId: "WEB" })).status, 404);
    const roomId = "!route-synthetic:sonar.invalid";
    await createMatrixRoom(roomId, userId, [userId, "@000000000000000000000000:sonar.invalid"], "direct");
    const roomPath = `/room?roomId=${encodeURIComponent(roomId)}&deviceId=WEB`;
    assert.equal((await request(roomPath)).status, 400);
    const scope = { roomId, deviceId: "WEB", revision: 0 };
    assert.equal((await message("/events/transaction", scope, "")).status, 401);
    assert.equal((await message("/events/transaction", scope, legacyCookie)).status, 401);
    assert.equal((await message("/events/transaction", scope)).status, 400);
    assert.equal((await message("/rooms/direct", { deviceId: "WEB", peerAccountId: String(peer._id) })).status, 400);
    // Synthetic-only first device initialization; this action is not exposed.
    await bootstrapMatrixDevice(accountId, sessionHash(rawSession), "sonar.invalid", "WEB");
    assert.equal((await message("/rooms/direct", { deviceId: "WEB", peerAccountId: accountId })).status, 400);
    assert.equal((await message("/rooms/direct", { deviceId: "WEB", peerAccountId: "000000000000000000000000" })).status, 400);
    const directRequests = await Promise.all(Array.from({ length: 3 }, () => message("/rooms/direct", { deviceId: "WEB", peerAccountId: String(peer._id) })));
    assert.ok(directRequests.every(response => response.status === 200));
    const directRooms = await Promise.all(directRequests.map(response => response.json()));
    assert.ok(directRooms.every(room => room.roomId === directRooms[0].roomId && room.kind === "direct" && room.members.includes(userId) && room.members.includes(`@${peer._id}:sonar.invalid`)));
    const snapshot = await (await request(roomPath)).json();
    assert.equal(snapshot.roomId, roomId);
    assert.equal(snapshot.revision, 1);
    assert.ok(snapshot.members.includes(userId));
    const ready = { ...scope, revision: 1 };
    assert.equal((await message("/events/transaction", scope)).status, 400);
    const token = (await (await message("/events/transaction", ready)).json()).token;
    const content = { algorithm: "m.megolm.v1.aes-sha2", ciphertext: "A".repeat(24), device_id: "WEB", sender_key: keys.keys["curve25519:WEB"], session_id: keys.keys["ed25519:WEB"] };
    const submitted = await (await message("/events/send", { ...ready, token, content })).json();
    assert.ok(submitted._id);
    assert.deepEqual(notifications[0].sort(), [userId, "@000000000000000000000000:sonar.invalid"].sort());
    assert.equal(JSON.stringify(notifications).includes(content.ciphertext), false);
    const duplicate = await (await message("/events/send", { ...ready, token, content })).json();
    assert.equal(duplicate.duplicate, true);
    assert.equal((await message("/events/send", { ...ready, token, content: { ...content, ciphertext: "B".repeat(24) } })).status, 400);
    const history = await (await message(`/events/history?roomId=${encodeURIComponent(roomId)}&deviceId=WEB`)).json();
    assert.equal(history.messages.length, 1);
    const attachmentToken = (await (await message("/events/transaction", ready)).json()).token;
    const header = Buffer.from(JSON.stringify({ ...ready, token: attachmentToken, content, attachmentId: "a".repeat(32) }));
    const prefix = Buffer.alloc(4); prefix.writeUInt32BE(header.length);
    const encryptedBytes = Buffer.from([0, 1, 255, 42, 128]);
    const frame = Buffer.concat([prefix, header, encryptedBytes]);
    const upload = (body, auth = cookie) => fetch(base + "/message/events/send-attachment", { method: "POST", headers: { ...(auth ? { Cookie: auth } : {}), "Content-Type": "application/octet-stream" }, body });
    assert.equal((await upload(frame, "")).status, 401);
    assert.equal((await upload(Buffer.from([0, 0, 0, 20, 123]))).status, 400);
    const attachment = await (await upload(frame)).json();
    assert.ok(attachment._id);
    assert.equal(Object.hasOwn(attachment, "attachmentCiphertext"), false);
    const downloadPath = `/events/attachment?roomId=${encodeURIComponent(roomId)}&deviceId=WEB&eventId=${attachment._id}`;
    const response = await message(downloadPath);
    assert.equal(response.status, 200);
    assert.equal(response.headers.get("cache-control"), "no-store");
    assert.deepEqual(Buffer.from(await response.arrayBuffer()), encryptedBytes);
    assert.equal((await message(downloadPath, null, "")).status, 401);
    assert.equal((await (await upload(frame)).json()).duplicate, true);
    const changedFrame = Buffer.from(frame); changedFrame[changedFrame.length - 1] ^= 1;
    assert.equal((await upload(changedFrame)).status, 400);
    assert.equal((await message("/events/pin", { ...ready, eventId: attachment._id, pinned: true })).status, 200);
    assert.equal((await message(downloadPath)).status, 200);
    assert.equal((await message("/events/pin", { ...ready, eventId: attachment._id, pinned: false })).status, 200);
    await MatrixRoomEvent.updateOne({ _id: attachment._id }, { $set: { expiresAt: new Date(0) } });
    assert.equal((await message(downloadPath)).status, 400);
    await MatrixRoomEvent.updateOne({ _id: attachment._id }, { $set: { expiresAt: new Date(Date.now() + 60000) } });
    assert.equal((await message("/events/delete", { ...ready, eventId: attachment._id })).status, 200);
    assert.equal((await MatrixRoomEvent.findById(attachment._id)), null);
    const beforePin = notifications.length;
    assert.equal((await (await message("/events/pin", { ...ready, eventId: submitted._id, pinned: true })).json()).expiresAt, null);
    assert.equal(notifications.length, beforePin + 1);
    await MatrixRoomEvent.insertMany(Array.from({ length: 55 }, () => ({ roomId, sender: userId, senderDevice: "WEB", visibleTo: [userId, "@000000000000000000000000:sonar.invalid"], content })));
    const recent = await (await message(`/events/history?roomId=${encodeURIComponent(roomId)}&deviceId=WEB&limit=5`)).json();
    const pins = await (await message(`/events/history?roomId=${encodeURIComponent(roomId)}&deviceId=WEB&limit=5&pinned=true`)).json();
    assert.equal(recent.messages.some(item => item._id === submitted._id), false);
    assert.deepEqual(pins.messages.map(item => item._id), [submitted._id]);
    assert.equal((await message("/events/delete", { ...ready, eventId: submitted._id })).status, 200);
    assert.equal(notifications.length, beforePin + 2);
    const queried = await (await message("/keys/query", { ...ready, users: [userId] })).json();
    assert.deepEqual(queried.device_keys[userId].WEB, keys);
    assert.equal((await message("/keys/query", { ...ready, users: ["@111111111111111111111111:sonar.invalid"] })).status, 400);
    assert.equal((await request(`/room?roomId=${encodeURIComponent(roomId)}&deviceId=OTHER`)).status, 400);
    const finalToken = (await (await message("/events/transaction", ready)).json()).token;
    const finalHeader = Buffer.from(JSON.stringify({ ...ready, token: finalToken, content, attachmentId: "b".repeat(32) }));
    const finalPrefix = Buffer.alloc(4); finalPrefix.writeUInt32BE(finalHeader.length);
    const finalAttachment = await (await upload(Buffer.concat([finalPrefix, finalHeader, encryptedBytes]))).json();
    const revokedPath = `/events/attachment?roomId=${encodeURIComponent(roomId)}&deviceId=WEB&eventId=${finalAttachment._id}`;
    assert.equal((await message(revokedPath)).status, 200);
    await revokeSessionMatrixDevice(accountId, sessionHash(rawSession), "sonar.invalid", "WEB", "WEB");
    assert.equal((await request(roomPath)).status, 400);
    assert.equal((await message(`/events/history?roomId=${encodeURIComponent(roomId)}&deviceId=WEB`)).status, 400);
    assert.equal((await message(revokedPath)).status, 400);
    assert.equal((await message("/rooms/direct", { deviceId: "WEB", peerAccountId: String(peer._id) })).status, 400);
    await LoginSession.deleteOne({ _id: sessionHash(rawSession) });
    assert.equal((await request("/identity")).status, 401);
  } finally {
    machine?.close();
    if (server) await new Promise(resolve => server.close(resolve));
    await mongoose.disconnect(); await db.stop();
  }
});
