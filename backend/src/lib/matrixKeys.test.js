import { test } from "node:test";
import "fake-indexeddb/auto";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { OlmMachine, UserId, DeviceId, RequestType, RoomId, EncryptionSettings, CollectStrategy, DeviceLists, DecryptionSettings, TrustRequirement } from "@matrix-org/matrix-sdk-crypto-wasm";
import mongoose from "mongoose";
import { MongoMemoryReplSet } from "mongodb-memory-server";
import MatrixDevice from "../models/matrixDevice.model.js";
import MatrixOneTimeKey from "../models/matrixOneTimeKey.model.js";
import MatrixToDevice from "../models/matrixToDevice.model.js";
import MatrixToDeviceTransaction from "../models/matrixToDeviceTransaction.model.js";
import MatrixRoom from "../models/matrixRoom.model.js";
import MatrixRoomEvent from "../models/matrixRoomEvent.model.js";
import MatrixRoomSession from "../models/matrixRoomSession.model.js";
import MatrixEventTransaction from "../models/matrixEventTransaction.model.js";
import { createDevice, uploadOneTimeKeys, queryDeviceKeys, claimOneTimeKey, revokeDevice } from "./matrixKeys.js";
import { enqueueToDevice, enqueueRoomKeyShares, readToDevice, acknowledgeToDevice } from "./matrixToDevice.js";
import { createMatrixRoom, setMatrixRoomMembers, issueMatrixEventTransaction, sendMatrixRoomEvent, matrixRoomHistory, readMatrixRoomAttachment, setMatrixRoomEventPinned, deleteMatrixRoomEvent, deleteMatrixCommunityRoom } from "./matrixRooms.js";
import { ensureMatrixRoomRevision } from "../../../frontend/src/lib/matrixRoomRevision.js";

// This test uses one isolated SDK store; browser tabs provide actual Web Locks.
Object.defineProperty(globalThis.navigator, "locks", { configurable: true, value: { request: (_name, _options, callback) => callback() } });

test("Matrix device keys and one-time claims work with the real crypto state machine", async () => {
  const db = await MongoMemoryReplSet.create({ replSet: { count: 1 } });
  let alice, bob;
  try {
    await mongoose.connect(db.getUri("sonar-matrix-key-tests"));
    await Promise.all([MatrixDevice.init(), MatrixOneTimeKey.init(), MatrixToDevice.init(), MatrixToDeviceTransaction.init(), MatrixRoom.init(), MatrixRoomEvent.init(), MatrixRoomSession.init(), MatrixEventTransaction.init()]);
    const aliceId = "@0123456789abcdef01234567:sonar.invalid";
    const bobId = "@abcdef0123456789abcdef01:sonar.invalid";
    alice = await OlmMachine.initialize(new UserId(aliceId), new DeviceId("ALICE"));
    bob = await OlmMachine.initialize(new UserId(bobId), new DeviceId("BOB"));
    const aliceRequests = await alice.outgoingRequests();
    const bobRequests = await bob.outgoingRequests();
    const aliceUpload = aliceRequests.find(request => request.type === RequestType.KeysUpload);
    const bobUpload = bobRequests.find(request => request.type === RequestType.KeysUpload);
    const aliceBody = JSON.parse(aliceUpload.body), bobBody = JSON.parse(bobUpload.body);
    await createDevice(aliceId, "ALICE", aliceBody.device_keys);
    await createDevice(bobId, "BOB", bobBody.device_keys);
    // Synthetic setup; real clients must authorize devices after verification.
    await MatrixDevice.updateMany({ userId: { $in: [aliceId, bobId] } }, { $set: { serverAuthorization: "authorized" } });
    await assert.rejects(createDevice(aliceId, "OTHER", aliceBody.device_keys));
    await assert.rejects(createDevice(aliceId, "ALICE", { ...aliceBody.device_keys, private_key: "never-store" }));
    const substitutedDeviceKey = structuredClone(aliceBody.device_keys);
    substitutedDeviceKey.keys["curve25519:ALICE"] = bobBody.device_keys.keys["curve25519:BOB"];
    await assert.rejects(createDevice(aliceId, "ALICE", substitutedDeviceKey), /Invalid device signature/);
    const badSignature = structuredClone(aliceBody.device_keys);
    const deviceSignature = badSignature.signatures[aliceId]["ed25519:ALICE"];
    badSignature.signatures[aliceId]["ed25519:ALICE"] = `${deviceSignature[0] === "A" ? "B" : "A"}${deviceSignature.slice(1)}`;
    await assert.rejects(createDevice(aliceId, "ALICE", badSignature), /Invalid device signature/);
    const firstBobKey = Object.keys(bobBody.one_time_keys)[0];
    const forgedOneTime = structuredClone(bobBody.one_time_keys[firstBobKey]);
    forgedOneTime.key = Object.values(aliceBody.one_time_keys)[0].key;
    await assert.rejects(uploadOneTimeKeys(bobId, "BOB", { [firstBobKey]: forgedOneTime }), /Invalid one-time key signature/);
    assert.equal(await MatrixOneTimeKey.countDocuments({ userId: bobId, deviceId: "BOB" }), 0);
    const aliceResponse = await uploadOneTimeKeys(aliceId, "ALICE", aliceBody.one_time_keys);
    const bobResponse = await uploadOneTimeKeys(bobId, "BOB", bobBody.one_time_keys);
    assert.equal(aliceResponse.one_time_key_counts.signed_curve25519, 50);
    assert.equal(bobResponse.one_time_key_counts.signed_curve25519, 50);
    assert.deepEqual(await uploadOneTimeKeys(bobId, "BOB", bobBody.one_time_keys), bobResponse);
    const duplicateUploads = await Promise.all([uploadOneTimeKeys(bobId, "BOB", bobBody.one_time_keys), uploadOneTimeKeys(bobId, "BOB", bobBody.one_time_keys)]);
    assert.ok(duplicateUploads.every(response => response.one_time_key_counts.signed_curve25519 === 50));
    const [firstId, secondId] = Object.keys(bobBody.one_time_keys);
    await assert.rejects(uploadOneTimeKeys(bobId, "BOB", { [firstId]: bobBody.one_time_keys[secondId] }), /cannot be replaced/);
    await assert.rejects(uploadOneTimeKeys(bobId, "BOB", { [firstId]: { ...bobBody.one_time_keys[firstId], private_key: "never-store" } }));
    await alice.markRequestAsSent(aliceUpload.id, aliceUpload.type, JSON.stringify(aliceResponse));
    await bob.markRequestAsSent(bobUpload.id, bobUpload.type, JSON.stringify(bobResponse));
    await alice.updateTrackedUsers([new UserId(bobId)]);
    const query = (await alice.outgoingRequests()).find(request => request.type === RequestType.KeysQuery);
    const queryUsers = Object.keys(JSON.parse(query.body).device_keys);
    const directory = await queryDeviceKeys(queryUsers);
    assert.equal(directory.device_keys[bobId].BOB.device_id, "BOB");
    await alice.markRequestAsSent(query.id, query.type, JSON.stringify(directory));
    const claim = await alice.getMissingSessions([new UserId(bobId)]);
    assert.ok(claim);
    const claimBody = JSON.parse(claim.body);
    assert.equal(claimBody.one_time_keys[bobId].BOB, "signed_curve25519");
    const claimed = await claimOneTimeKey(bobId, "BOB", "signed_curve25519");
    assert.equal(Object.keys(claimed.one_time_keys[bobId].BOB).length, 1);
    await alice.markRequestAsSent(claim.id, claim.type, JSON.stringify(claimed));
    assert.equal(await alice.getMissingSessions([new UserId(bobId)]), null);
    await bob.updateTrackedUsers([new UserId(aliceId)]);
    const bobQuery = (await bob.outgoingRequests()).find(request => request.type === RequestType.KeysQuery);
    await bob.markRequestAsSent(bobQuery.id, bobQuery.type, JSON.stringify(await queryDeviceKeys(Object.keys(JSON.parse(bobQuery.body).device_keys))));
    const room = "!synthetic-room:sonar.invalid";
    await createMatrixRoom(room, aliceId, [aliceId, bobId], "community");
    const store = `sonar-matrix-v2-${"a".repeat(32)}`;
    await ensureMatrixRoomRevision({ RoomId }, alice, store, room, 0);
    const settings = new EncryptionSettings();
    // This is a synthetic interoperability test, not the production trust policy.
    settings.sharingStrategy = CollectStrategy.allDevices();
    const shares = await alice.shareRoomKey(new RoomId(room), [new UserId(bobId)], settings);
    assert.ok(shares.length > 0);
    let shareMessages;
    for (const share of shares) {
      const messages = JSON.parse(share.body).messages;
      shareMessages = messages;
      await assert.rejects(enqueueRoomKeyShares(room, 0, aliceId, "ALICE", "outsider-share", share.event_type, { "@111111111111111111111111:sonar.invalid": messages[bobId] }), /Room membership changed/);
      await MatrixDevice.updateOne({ userId: bobId, deviceId: "BOB" }, { $set: { serverAuthorization: "pending" } });
      await assert.rejects(enqueueRoomKeyShares(room, 0, aliceId, "ALICE", "pending-share", share.event_type, messages), /Device key mismatch/);
      await MatrixDevice.updateOne({ userId: bobId, deviceId: "BOB" }, { $set: { serverAuthorization: "authorized" } });
      await Promise.all([enqueueRoomKeyShares(room, 0, aliceId, "ALICE", share.txn_id, share.event_type, messages), enqueueRoomKeyShares(room, 0, aliceId, "ALICE", share.txn_id, share.event_type, messages)]);
      const queued = await readToDevice(bobId, "BOB");
      assert.equal(queued.length, 1);
      assert.deepEqual(await readToDevice(aliceId, "ALICE"), []);
      await acknowledgeToDevice(aliceId, "ALICE", [queued[0].id]);
      assert.equal((await readToDevice(bobId, "BOB")).length, 1);
      await bob.receiveSyncChanges(JSON.stringify(queued.map(row => row.event)), new DeviceLists(), new Map([["signed_curve25519", 49]]), undefined, new DecryptionSettings(TrustRequirement.Untrusted));
      await acknowledgeToDevice(bobId, "BOB", [queued[0].id]);
      await enqueueRoomKeyShares(room, 0, aliceId, "ALICE", share.txn_id, share.event_type, messages);
      assert.deepEqual(await readToDevice(bobId, "BOB"), []);
      const altered = structuredClone(messages);
      altered[bobId].BOB.ciphertext[Object.keys(altered[bobId].BOB.ciphertext)[0]].body += "A";
      await assert.rejects(enqueueRoomKeyShares(room, 0, aliceId, "ALICE", share.txn_id, share.event_type, altered), /cannot be replaced/);
      await assert.rejects(enqueueToDevice(aliceId, "ALICE", share.txn_id, share.event_type, messages), /cannot be replaced/);
      await assert.rejects(enqueueToDevice(aliceId, "ALICE", "invalid-plaintext", "m.room.encrypted", { [bobId]: { BOB: { body: "secret" } } }));
      await alice.markRequestAsSent(share.id, share.type, "{}");
    }
    const secret = "synthetic encrypted message";
    const encrypted = JSON.parse(await alice.encryptRoomEvent(new RoomId(room), "m.room.message", JSON.stringify({ msgtype: "m.text", body: secret })));
    assert.ok(!JSON.stringify(encrypted).includes(secret));
    const outsider = "@111111111111111111111111:sonar.invalid";
    const initialToken = (await issueMatrixEventTransaction(room, aliceId, "ALICE", 0)).token;
    const simultaneous = await Promise.all(Array.from({ length: 4 }, () => sendMatrixRoomEvent(room, aliceId, "ALICE", 0, encrypted, initialToken)));
    const stored = simultaneous[0];
    assert.equal(new Set(simultaneous.map(item => String(item._id))).size, 1);
    assert.equal(await MatrixRoomEvent.countDocuments({ roomId: room }), 1);
    const attachmentBytes = Buffer.from([0, 255, 42, 10, 128]);
    const attachmentToken = (await issueMatrixEventTransaction(room, aliceId, "ALICE", 0)).token;
    const attachmentEvent = await sendMatrixRoomEvent(room, aliceId, "ALICE", 0, encrypted, attachmentToken, attachmentBytes, "a".repeat(32));
    assert.equal(Object.hasOwn(attachmentEvent, "attachmentCiphertext"), false);
    assert.deepEqual(await readMatrixRoomAttachment(room, bobId, String(attachmentEvent._id)), attachmentBytes);
    assert.equal((await matrixRoomHistory(room, bobId)).messages.some(item => Object.hasOwn(item, "attachmentCiphertext")), false);
    await assert.rejects(readMatrixRoomAttachment(room, outsider, String(attachmentEvent._id)), /Room unavailable/);
    await assert.rejects(sendMatrixRoomEvent(room, aliceId, "ALICE", 0, encrypted, attachmentToken, Buffer.from([1]), "a".repeat(32)), /cannot be replaced/);
    assert.equal((await sendMatrixRoomEvent(room, aliceId, "ALICE", 0, encrypted, attachmentToken, attachmentBytes, "a".repeat(32))).duplicate, true);
    await setMatrixRoomEventPinned(room, bobId, String(attachmentEvent._id), true);
    assert.deepEqual(await readMatrixRoomAttachment(room, bobId, String(attachmentEvent._id)), attachmentBytes);
    await setMatrixRoomEventPinned(room, bobId, String(attachmentEvent._id), false);
    await MatrixRoomEvent.updateOne({ _id: attachmentEvent._id }, { $set: { expiresAt: new Date(0) } });
    await assert.rejects(readMatrixRoomAttachment(room, bobId, String(attachmentEvent._id)), /Attachment unavailable/);
    await MatrixRoomEvent.deleteOne({ _id: attachmentEvent._id });
    const quotaRoom = "!attachment-quota:sonar.invalid";
    await createMatrixRoom(quotaRoom, aliceId, [aliceId, bobId], "community");
    const quotaTokens = await Promise.all([issueMatrixEventTransaction(room, aliceId, "ALICE", 0), issueMatrixEventTransaction(quotaRoom, aliceId, "ALICE", 0)]);
    const previousLimit = process.env.MATRIX_ATTACHMENT_GLOBAL_LIMIT_BYTES;
    try {
      process.env.MATRIX_ATTACHMENT_GLOBAL_LIMIT_BYTES = "8";
      const attempts = await Promise.allSettled([
        sendMatrixRoomEvent(room, aliceId, "ALICE", 0, encrypted, quotaTokens[0].token, attachmentBytes, "b".repeat(32)),
        sendMatrixRoomEvent(quotaRoom, aliceId, "ALICE", 0, encrypted, quotaTokens[1].token, attachmentBytes, "c".repeat(32)),
      ]);
      assert.equal(attempts.filter(item => item.status === "fulfilled").length, 1);
      assert.equal(attempts.filter(item => item.status === "rejected").length, 1);
      assert.match(attempts.find(item => item.status === "rejected").reason.message, /Global attachment capacity reached/);
      const winner = attempts.find(item => item.status === "fulfilled").value;
      await deleteMatrixRoomEvent(winner.roomId, aliceId, String(winner._id));
      const retryIndex = attempts.findIndex(item => item.status === "rejected");
      const retryRoom = retryIndex === 0 ? room : quotaRoom;
      const retry = await sendMatrixRoomEvent(retryRoom, aliceId, "ALICE", 0, encrypted, quotaTokens[retryIndex].token, attachmentBytes, (retryIndex === 0 ? "b" : "c").repeat(32));
      await deleteMatrixRoomEvent(retryRoom, aliceId, String(retry._id));
    } finally {
      if (previousLimit === undefined) delete process.env.MATRIX_ATTACHMENT_GLOBAL_LIMIT_BYTES; else process.env.MATRIX_ATTACHMENT_GLOBAL_LIMIT_BYTES = previousLimit;
      await deleteMatrixCommunityRoom(quotaRoom, aliceId);
    }
    const expiredToken = (await issueMatrixEventTransaction(room, aliceId, "ALICE", 0)).token;
    await MatrixEventTransaction.updateOne({ tokenHash: createHash("sha256").update(expiredToken).digest("hex") }, { $set: { expiresAt: new Date(0) } });
    await assert.rejects(sendMatrixRoomEvent(room, aliceId, "ALICE", 0, encrypted, expiredToken), /expired/);
    assert.ok(!JSON.stringify(stored).includes(secret));
    await assert.rejects(sendMatrixRoomEvent(room, aliceId, "ALICE", 0, { ...encrypted, plaintext: secret }, initialToken), /Invalid encrypted/);
    await assert.rejects(sendMatrixRoomEvent(room, bobId, "BOB", 0, encrypted, initialToken), /Invalid encrypted/);
    assert.equal((await matrixRoomHistory(room, bobId)).messages.length, 1);
    const extraContent = JSON.parse(await alice.encryptRoomEvent(new RoomId(room), "m.room.message", JSON.stringify({ msgtype: "m.text", body: "synthetic page two" })));
    await assert.rejects(sendMatrixRoomEvent(room, aliceId, "ALICE", 0, extraContent, initialToken), /cannot be replaced/);
    const extraToken = (await issueMatrixEventTransaction(room, aliceId, "ALICE", 0)).token;
    const extra = await sendMatrixRoomEvent(room, aliceId, "ALICE", 0, extraContent, extraToken);
    const firstPage = await matrixRoomHistory(room, bobId, { limit: 1 });
    assert.equal(firstPage.hasMore, true);
    assert.equal(String(firstPage.messages[0]._id), String(extra._id));
    const olderPage = await matrixRoomHistory(room, bobId, { limit: 1, before: firstPage.nextCursor });
    assert.equal(String(olderPage.messages[0]._id), String(stored._id));
    await deleteMatrixRoomEvent(room, aliceId, String(extra._id));
    const retryDeleted = await sendMatrixRoomEvent(room, aliceId, "ALICE", 0, extraContent, extraToken);
    assert.equal(retryDeleted.unavailable, true);
    assert.equal(await MatrixRoomEvent.countDocuments({ roomId: room }), 1);
    await assert.rejects(matrixRoomHistory(room, outsider), /Room unavailable/);
    const pinned = await setMatrixRoomEventPinned(room, bobId, String(stored._id), true);
    assert.equal(pinned.pinned, true); assert.equal(pinned.expiresAt, null);
    assert.equal((await matrixRoomHistory(room, bobId, { pinned: "true" })).messages.length, 1);
    const repeatedPin = await setMatrixRoomEventPinned(room, bobId, String(stored._id), true);
    assert.equal(repeatedPin.expiresAt, null);
    const unpinned = await setMatrixRoomEventPinned(room, bobId, String(stored._id), false);
    assert.ok(new Date(unpinned.expiresAt).getTime() > Date.now() + 6 * 86400000);
    const deadline = new Date(unpinned.expiresAt).getTime();
    const repeatedUnpin = await setMatrixRoomEventPinned(room, bobId, String(stored._id), false);
    assert.equal(new Date(repeatedUnpin.expiresAt).getTime(), deadline);
    assert.ok((await MatrixRoomEvent.collection.indexes()).some(index => index.key.expiresAt === 1 && index.expireAfterSeconds === 0));
    const staleToken = (await issueMatrixEventTransaction(room, aliceId, "ALICE", 0)).token;
    await setMatrixRoomMembers(room, aliceId, 0, [aliceId, bobId, outsider]);
    await assert.rejects(enqueueRoomKeyShares(room, 0, aliceId, "ALICE", "stale-share", "m.room.encrypted", shareMessages), /Room membership changed/);
    const retryAfterChange = await sendMatrixRoomEvent(room, aliceId, "ALICE", 0, encrypted, initialToken);
    assert.equal(retryAfterChange.duplicate, true);
    assert.equal(String(retryAfterChange._id), String(stored._id));
    assert.equal((await matrixRoomHistory(room, outsider)).messages.length, 0);
    await assert.rejects(sendMatrixRoomEvent(room, aliceId, "ALICE", 0, encrypted, staleToken), /membership changed/);
    const rotatedToken = (await issueMatrixEventTransaction(room, aliceId, "ALICE", 1)).token;
    await assert.rejects(sendMatrixRoomEvent(room, aliceId, "ALICE", 1, encrypted, rotatedToken), /key must rotate/);
    assert.equal(await ensureMatrixRoomRevision({ RoomId }, alice, store, room, 1), true);
    const rotatedShares = await alice.shareRoomKey(new RoomId(room), [new UserId(bobId)], settings);
    for (const share of rotatedShares) await alice.markRequestAsSent(share.id, share.type, "{}");
    const rotated = JSON.parse(await alice.encryptRoomEvent(new RoomId(room), "m.room.message", JSON.stringify({ msgtype: "m.text", body: "second synthetic message" })));
    assert.notEqual(rotated.session_id, encrypted.session_id);
    const secondEvent = await sendMatrixRoomEvent(room, aliceId, "ALICE", 1, rotated, rotatedToken);
    assert.equal((await matrixRoomHistory(room, outsider)).messages.length, 1);
    await assert.rejects(deleteMatrixRoomEvent(room, bobId, String(secondEvent._id)), /Event unavailable/);
    await deleteMatrixRoomEvent(room, aliceId, String(secondEvent._id));
    const raceToken = (await issueMatrixEventTransaction(room, aliceId, "ALICE", 1)).token;
    const [racingSend, racingRemoval, racingHistory] = await Promise.allSettled([
      sendMatrixRoomEvent(room, aliceId, "ALICE", 1, rotated, raceToken),
      setMatrixRoomMembers(room, aliceId, 1, [aliceId, outsider]),
      matrixRoomHistory(room, bobId),
    ]);
    assert.equal(racingRemoval.status, "fulfilled");
    if (racingHistory.status === "fulfilled") assert.ok(racingHistory.value.messages.every(event => event.visibleTo.includes(bobId)));
    else assert.match(racingHistory.reason.message, /Room unavailable/);
    if (racingSend.status === "fulfilled") {
      assert.ok(racingSend.value.visibleTo.includes(bobId));
      await deleteMatrixRoomEvent(room, aliceId, String(racingSend.value._id));
    } else assert.match(racingSend.reason.message, /membership changed/);
    await assert.rejects(matrixRoomHistory(room, bobId), /Room unavailable/);
    await assert.rejects(setMatrixRoomEventPinned(room, bobId, String(stored._id), true), /Room unavailable/);
    await MatrixRoomEvent.updateOne({ _id: stored._id }, { $set: { expiresAt: new Date(0) } });
    assert.equal((await matrixRoomHistory(room, aliceId)).messages.length, 0);
    assert.equal((await sendMatrixRoomEvent(room, aliceId, "ALICE", 0, encrypted, initialToken)).unavailable, true);
    await assert.rejects(setMatrixRoomEventPinned(room, aliceId, String(stored._id), true), /Event unavailable/);
    await assert.rejects(deleteMatrixCommunityRoom(room, outsider), /Room unavailable/);
    await deleteMatrixCommunityRoom(room, aliceId);
    assert.equal(await MatrixRoomEvent.countDocuments({ roomId: room }), 0);
    assert.equal(await MatrixRoomSession.countDocuments({ roomId: room }), 0);
    assert.equal(await MatrixEventTransaction.countDocuments({ roomId: room }), 0);
    const event = { type: "m.room.encrypted", event_id: "$synthetic", sender: aliceId, origin_server_ts: 1700000000000, content: encrypted };
    const decrypted = await bob.decryptRoomEvent(JSON.stringify(event), new RoomId(room), new DecryptionSettings(TrustRequirement.Untrusted));
    assert.equal(JSON.parse(decrypted.event).content.body, secret);
    const wrongRecipient = structuredClone(shareMessages);
    const wrongContent = wrongRecipient[bobId].BOB;
    const originalKey = Object.keys(wrongContent.ciphertext)[0];
    const originalCipher = wrongContent.ciphertext[originalKey];
    wrongContent.ciphertext = { [aliceBody.device_keys.keys["curve25519:ALICE"]]: originalCipher };
    await assert.rejects(enqueueToDevice(aliceId, "ALICE", "wrong-recipient", "m.room.encrypted", wrongRecipient), /Device key mismatch/);
    await enqueueToDevice(aliceId, "ALICE", "expires", "m.room.encrypted", shareMessages);
    await MatrixToDevice.updateMany({ recipient: bobId }, { $set: { expiresAt: new Date(0) } });
    assert.deepEqual(await readToDevice(bobId, "BOB"), []);
    await enqueueToDevice(aliceId, "ALICE", "revoke-target", "m.room.encrypted", shareMessages);
    assert.equal((await readToDevice(bobId, "BOB")).length, 1);
    const concurrent = await Promise.all(Array.from({ length: 49 }, () => claimOneTimeKey(bobId, "BOB", "signed_curve25519")));
    const ids = concurrent.map(response => Object.keys(response.one_time_keys[bobId].BOB)[0]);
    assert.equal(new Set(ids).size, 49);
    assert.deepEqual((await claimOneTimeKey(bobId, "BOB", "signed_curve25519")).one_time_keys, {});
    const revocations = await Promise.all([revokeDevice(aliceId, "ALICE"), revokeDevice(aliceId, "ALICE")]);
    assert.deepEqual(revocations.sort(), [false, true]);
    assert.equal(await revokeDevice(aliceId, "ALICE"), false);
    assert.deepEqual((await queryDeviceKeys([aliceId])).device_keys[aliceId], {});
    assert.deepEqual((await claimOneTimeKey(aliceId, "ALICE", "signed_curve25519")).one_time_keys, {});
    await assert.rejects(uploadOneTimeKeys(aliceId, "ALICE", aliceBody.one_time_keys), /Unknown device/);
    await assert.rejects(createDevice(aliceId, "ALICE", aliceBody.device_keys));
    await assert.rejects(claimOneTimeKey({ toString: () => bobId }, "BOB", "signed_curve25519"), /Invalid key claim/);
    assert.equal(await MatrixOneTimeKey.countDocuments({ userId: bobId, deviceId: "BOB", claimedAt: null }), 0);
    assert.equal((await uploadOneTimeKeys(bobId, "BOB", bobBody.one_time_keys)).one_time_key_counts.signed_curve25519, 0);
    assert.deepEqual((await claimOneTimeKey(bobId, "BOB", "signed_curve25519")).one_time_keys, {});
    const raceMessages = structuredClone(shareMessages);
    raceMessages[bobId].BOB.sender_key = bobBody.device_keys.keys["curve25519:BOB"];
    const pendingIds = (await readToDevice(bobId, "BOB")).map(item => item.id);
    const [racingEnqueue, racingRevoke, racingRead, racingAck] = await Promise.allSettled([
      enqueueToDevice(bobId, "BOB", "revoke-race", "m.room.encrypted", raceMessages),
      revokeDevice(bobId, "BOB"),
      readToDevice(bobId, "BOB"),
      acknowledgeToDevice(bobId, "BOB", pendingIds),
    ]);
    assert.equal(racingRevoke.status, "fulfilled");
    assert.equal(racingRevoke.value, true);
    if (racingEnqueue.status === "rejected") assert.match(racingEnqueue.reason.message, /Unknown sender device|Device key mismatch/);
    for (const result of [racingRead, racingAck]) if (result.status === "rejected") assert.match(result.reason.message, /Unknown device/);
    assert.equal(await MatrixToDevice.countDocuments({ recipient: bobId, deviceId: "BOB" }), 0);
    await assert.rejects(readToDevice(bobId, "BOB"), /Unknown device/);
    await assert.rejects(acknowledgeToDevice(bobId, "BOB", pendingIds), /Unknown device/);
  } finally {
    alice?.close(); bob?.close();
    await mongoose.disconnect();
    await db.stop();
  }
});
