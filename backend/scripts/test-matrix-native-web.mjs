// Synthetic cross-SDK test against an isolated in-memory MongoDB replica set.
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { randomBytes } from "node:crypto";
import { createInterface } from "node:readline";
import { dirname, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import mongoose from "mongoose";
import express from "express";
import { MongoMemoryReplSet } from "mongodb-memory-server";
import { OlmMachine, UserId, DeviceId, RequestType, RoomId, EncryptionSettings, CollectStrategy, DeviceLists, DecryptionSettings, TrustRequirement } from "@matrix-org/matrix-sdk-crypto-wasm";
import MatrixDevice from "../src/models/matrixDevice.model.js";
import MatrixOneTimeKey from "../src/models/matrixOneTimeKey.model.js";
import MatrixToDevice from "../src/models/matrixToDevice.model.js";
import MatrixToDeviceTransaction from "../src/models/matrixToDeviceTransaction.model.js";
import MatrixRoom from "../src/models/matrixRoom.model.js";
import MatrixRoomEvent from "../src/models/matrixRoomEvent.model.js";
import MatrixRoomSession from "../src/models/matrixRoomSession.model.js";
import MatrixEventTransaction from "../src/models/matrixEventTransaction.model.js";
import User from "../src/models/user.model.js";
import LoginSession from "../src/models/loginSession.model.js";
import MatrixBindingChallenge from "../src/models/matrixBindingChallenge.model.js";
import MatrixEnrollment from "../src/models/matrixEnrollment.model.js";
import MatrixAccount from "../src/models/matrixAccount.model.js";
import { uploadSessionOneTimeKeys, querySessionRoomDeviceKeys, claimSessionRoomOneTimeKey } from "../src/lib/matrixKeys.js";
import { enqueueSessionRoomKeyShares, readSessionToDevice, acknowledgeSessionToDevice, readSessionRoomToDevice, acknowledgeSessionRoomToDevice } from "../src/lib/matrixToDevice.js";
import { issueMatrixBindingChallenge, bindMatrixDevice } from "../src/lib/matrixSessionBinding.js";
import { beginMatrixEnrollment, completeMatrixEnrollment, bootstrapMatrixDevice } from "../src/lib/matrixEnrollment.js";
import { signMatrixEnrollment } from "../../frontend/src/lib/matrixEnrollment.js";
import { signMatrixBinding } from "../../frontend/src/lib/matrixBinding.js";
import { createMatrixRoom, issueSessionMatrixEventTransaction, sendSessionMatrixRoomEvent, sessionMatrixRoomHistory } from "../src/lib/matrixRooms.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const nativeExe = process.env.SONAR_MATRIX_PROBE || resolve(root, "desktop/target/debug/examples/matrix_web_probe.exe");
const webId = "@0123456789abcdef01234567:sonar.invalid", nativeId = "@abcdef0123456789abcdef01:sonar.invalid";
const accountId = "0123456789abcdef01234567", domain = "sonar.invalid", sessionId = randomBytes(32).toString("hex");
const nativeAccount = "abcdef0123456789abcdef01", nativeSession = randomBytes(32).toString("hex");
const db = await MongoMemoryReplSet.create({ replSet: { count: 1 } });
const tempRoot = await mkdtemp(resolve(tmpdir(), "sonar-matrix-probe-"));
let child, web, httpServer;
try {
  await mongoose.connect(db.getUri("sonar-matrix-native-web-tests"));
  const fixture = express(); fixture.use(express.json());
  let failFirstAcknowledgement = true;
  fixture.get("/api/matrix/messages/shares/inbox", async (_req, res) => { try { res.json({ events: await readSessionRoomToDevice(nativeAccount, nativeSession, domain, "NATIVE", "!synthetic-room:sonar.invalid") }); } catch { res.sendStatus(400); } });
  fixture.post("/api/matrix/messages/shares/ack", async (req, res) => { try { if (failFirstAcknowledgement) { failFirstAcknowledgement = false; return res.sendStatus(503); } await acknowledgeSessionRoomToDevice(nativeAccount, nativeSession, domain, "NATIVE", "!synthetic-room:sonar.invalid", req.body.ids); res.json({ acknowledged: true }); } catch { res.sendStatus(400); } });
  await new Promise(done => { httpServer = fixture.listen(0, "127.0.0.1", done); });
  await Promise.all([MatrixDevice.init(), MatrixOneTimeKey.init(), MatrixToDevice.init(), MatrixToDeviceTransaction.init(), MatrixRoom.init(), MatrixRoomEvent.init(), MatrixRoomSession.init(), MatrixEventTransaction.init(), User.init(), LoginSession.init(), MatrixBindingChallenge.init(), MatrixEnrollment.init(), MatrixAccount.init()]);
  const start = (args = []) => {
    child = spawn(nativeExe, args, { env: { ...process.env, SONAR_MATRIX_PROBE_ROOT: tempRoot, SONAR_MATRIX_INBOX_TEST_BASE: `http://127.0.0.1:${httpServer.address().port}` }, stdio: ["pipe", "pipe", "pipe"] });
    let stderr = ""; child.stderr.on("data", chunk => { stderr += chunk; });
    const lines = createInterface({ input: child.stdout })[Symbol.asyncIterator]();
    const exited = new Promise((resolve, reject) => { child.once("error", reject); child.once("exit", code => resolve(code)); });
    const next = async () => {
      let timer;
      try {
        const result = await Promise.race([lines.next(), new Promise((_, reject) => { timer = setTimeout(() => reject(new Error("Native Matrix probe timed out")), 20000); })]);
        if (result.done) throw new Error(`Native Matrix probe stopped: ${stderr}`);
        return JSON.parse(result.value);
      } finally { clearTimeout(timer); }
    };
    return { next, exited };
  };
  let probe = start();
  let next = probe.next;
  const nativeUpload = await next();
  assert.equal(nativeUpload.type, "upload");
  web = await OlmMachine.initialize(new UserId(webId), new DeviceId("WEB"));
  const upload = (await web.outgoingRequests()).find(request => request.type === RequestType.KeysUpload);
  const webBody = JSON.parse(upload.body);
  await User.create({ _id: accountId, fullName: "Synthetic web", email: "matrix-web@example.invalid", password: "unused-test-hash" });
  await User.create({ _id: nativeAccount, fullName: "Synthetic native", email: "matrix-native@example.invalid", password: "unused-test-hash" });
  await LoginSession.create({ _id: sessionId, userId: accountId, sessionVersion: 0, method: "password", expiresAt: new Date(Date.now() + 60000) });
  await LoginSession.create({ _id: nativeSession, userId: nativeAccount, sessionVersion: 0, method: "password", expiresAt: new Date(Date.now() + 60000) });
  const webEnrollment = await beginMatrixEnrollment(accountId, sessionId, domain, "WEB", webBody.device_keys);
  const webEnrollmentSignature = await signMatrixEnrollment(web, webId, "WEB", webBody.device_keys, { ...webEnrollment, expiresAt: webEnrollment.expiresAt.toISOString() });
  assert.equal((await completeMatrixEnrollment(accountId, sessionId, domain, "WEB", webEnrollment.token, webEnrollmentSignature)).serverAuthorization, "pending");
  const enrollment = await beginMatrixEnrollment(nativeAccount, nativeSession, domain, "NATIVE", nativeUpload.body.device_keys);
  child.stdin.write(JSON.stringify({ token: enrollment.token, message: enrollment.message, expiresUnixMs: enrollment.expiresAt.getTime() }) + "\n");
  const enrollmentProof = await next();
  assert.equal(enrollmentProof.type, "enrollment");
  assert.equal((await completeMatrixEnrollment(nativeAccount, nativeSession, domain, "NATIVE", enrollment.token, enrollmentProof.signature)).serverAuthorization, "pending");
  const binding = await issueMatrixBindingChallenge(accountId, sessionId, webId, "WEB");
  const signature = await signMatrixBinding(web, webId, "WEB", { ...binding, expiresAt: binding.expiresAt.toISOString() });
  await bindMatrixDevice(accountId, sessionId, webId, "WEB", binding.token, signature);
  await bootstrapMatrixDevice(accountId, sessionId, domain, "WEB");
  const room = "!synthetic-room:sonar.invalid";
  const webUploadResponse = await uploadSessionOneTimeKeys(accountId, sessionId, domain, "WEB", webBody.one_time_keys);
  const nativeBinding = await issueMatrixBindingChallenge(nativeAccount, nativeSession, nativeId, "NATIVE");
  child.stdin.write(JSON.stringify({ token: nativeBinding.token, message: nativeBinding.message, expiresUnixMs: nativeBinding.expiresAt.getTime() }) + "\n");
  const proof = await next();
  assert.equal(proof.type, "binding");
  await bindMatrixDevice(nativeAccount, nativeSession, nativeId, "NATIVE", nativeBinding.token, proof.signature);
  await bootstrapMatrixDevice(nativeAccount, nativeSession, domain, "NATIVE");
  await createMatrixRoom(room, nativeId, [nativeId, webId], "direct");
  const nativeUploadResponse = await uploadSessionOneTimeKeys(nativeAccount, nativeSession, domain, "NATIVE", nativeUpload.body.one_time_keys);
  await web.markRequestAsSent(upload.id, upload.type, JSON.stringify(webUploadResponse));
  child.stdin.write(JSON.stringify({ upload: nativeUploadResponse, query: await querySessionRoomDeviceKeys(nativeAccount, nativeSession, domain, "NATIVE", room, 0, [webId]) }) + "\n");
  assert.equal((await next()).type, "ready");
  await web.updateTrackedUsers([new UserId(nativeId)]);
  const query = (await web.outgoingRequests()).find(request => request.type === RequestType.KeysQuery);
  await web.markRequestAsSent(query.id, query.type, JSON.stringify(await querySessionRoomDeviceKeys(accountId, sessionId, domain, "WEB", room, 0, [nativeId])));
  const claim = await web.getMissingSessions([new UserId(nativeId)]);
  assert.ok(claim);
  await web.markRequestAsSent(claim.id, claim.type, JSON.stringify(await claimSessionRoomOneTimeKey(accountId, sessionId, domain, "WEB", room, 0, nativeId, "NATIVE", "signed_curve25519")));
  const settings = new EncryptionSettings();
  // Explicitly relaxed trust only for this synthetic interoperability test.
  settings.sharingStrategy = CollectStrategy.allDevices();
  const shares = await web.shareRoomKey(new RoomId(room), [new UserId(nativeId)], settings);
  assert.equal(shares.length, 1);
  const share = shares[0];
  await enqueueSessionRoomKeyShares(accountId, sessionId, domain, room, 0, "WEB", share.txn_id, share.event_type, JSON.parse(share.body).messages);
  const queued = await readSessionToDevice(nativeAccount, nativeSession, domain, "NATIVE");
  assert.equal(queued.length, 1);
  await web.markRequestAsSent(share.id, share.type, "{}");
  const secret = "synthetic web to native message";
  const content = JSON.parse(await web.encryptRoomEvent(new RoomId(room), "m.room.message", JSON.stringify({ msgtype: "m.text", body: secret })));
  assert.ok(!JSON.stringify(content).includes(secret));
  const event = { type: "m.room.encrypted", event_id: "$synthetic", sender: webId, origin_server_ts: 1700000000000, content };
  child.stdin.write(JSON.stringify({ toDevice: queued[0].event, event }) + "\n");
  const result = await next();
  assert.equal(result.type, "result");
  assert.equal(result.event.content.body, secret);
  assert.equal((await readSessionToDevice(nativeAccount, nativeSession, domain, "NATIVE")).length, 0);
  assert.equal(failFirstAcknowledgement, false);
  const closed = await next();
  assert.equal(closed.type, "closed");
  assert.equal(await probe.exited, 0);
  probe = start([closed.name]);
  next = probe.next;
  assert.equal((await next()).type, "reopened");
  child.stdin.write(JSON.stringify({ event }) + "\n");
  const history = await next();
  assert.equal(history.type, "history");
  assert.equal(history.event.content.body, secret);
  const nativeShare = await next();
  assert.equal(nativeShare.type, "share");
  await enqueueSessionRoomKeyShares(nativeAccount, nativeSession, domain, room, 0, "NATIVE", nativeShare.txnId, nativeShare.eventType, nativeShare.messages);
  const webQueue = await readSessionToDevice(accountId, sessionId, domain, "WEB");
  assert.equal(webQueue.length, 1);
  await web.receiveSyncChanges(JSON.stringify(webQueue.map(item => item.event)), new DeviceLists(), new Map([["signed_curve25519", 50]]), undefined, new DecryptionSettings(TrustRequirement.Untrusted));
  await acknowledgeSessionToDevice(accountId, sessionId, domain, "WEB", [webQueue[0].id]);
  child.stdin.write(JSON.stringify({ type: "ack" }) + "\n");
  const nativeEvent = await next();
  assert.equal(nativeEvent.type, "encrypted");
  assert.ok(!JSON.stringify(nativeEvent.content).includes("synthetic native to web message"));
  const transaction = await issueSessionMatrixEventTransaction(nativeAccount, nativeSession, domain, room, "NATIVE", 0);
  await sendSessionMatrixRoomEvent(nativeAccount, nativeSession, domain, room, "NATIVE", 0, nativeEvent.content, transaction.token);
  const stored = (await sessionMatrixRoomHistory(accountId, sessionId, domain, room, "WEB")).messages;
  assert.equal(stored.length, 1);
  const decoded = await web.decryptRoomEvent(JSON.stringify({ type: "m.room.encrypted", event_id: "$native-synthetic", sender: nativeId, origin_server_ts: 1700000000001, content: stored[0].content }), new RoomId(room), new DecryptionSettings(TrustRequirement.Untrusted));
  assert.equal(JSON.parse(decoded.event).content.body, "synthetic native to web message");
  await LoginSession.deleteOne({ _id: sessionId });
  await assert.rejects(sessionMatrixRoomHistory(accountId, sessionId, domain, room, "WEB"), /Session unavailable/);
  await assert.rejects(querySessionRoomDeviceKeys(accountId, sessionId, domain, "WEB", room, 0, [nativeId]), /Session unavailable/);
  await assert.rejects(readSessionToDevice(accountId, sessionId, domain, "WEB"), /Session unavailable/);
  assert.equal(await probe.exited, 0);
  console.log("PASS: Matrix web and native Rust SDKs exchanged encrypted messages across a native process restart and protected store reopen.");
} finally {
  if (httpServer) await new Promise(done => httpServer.close(done));
  if (child && child.exitCode === null && child.signalCode === null) {
    const exited = new Promise(resolve => child.once("exit", resolve));
    child.kill();
    await exited;
  }
  web?.close();
  await mongoose.disconnect(); await db.stop();
  if (resolve(tempRoot).startsWith(resolve(tmpdir()) + sep) && dirname(resolve(tempRoot)) === resolve(tmpdir())) await rm(tempRoot, { recursive: true, force: true });
}
